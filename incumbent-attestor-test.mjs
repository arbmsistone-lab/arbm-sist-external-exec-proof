import assert from 'node:assert/strict';
import {attestDiscovery} from './incumbent-attestor.mjs';
const now=new Date('2026-09-08T13:00:00Z');
const routes=[{id:'free-primary',configured:true,endpoint:'x'},{id:'free-fallback',configured:true,endpoint:'y'}];
const configured=attestDiscovery({routes,evidence:null},now);
assert.equal(configured.verifiedCount,0);
assert.equal(configured.routes[0].state,'CONFIGURED_UNATTESTED');
const evidence={providerCostUsd:0,sourceCommit:'abc123',observedAt:'2026-09-08T12:00:00Z',validPatch:true,providerCallLedger:[{route:'free-primary',status:'ok',model:'model-free',pipeline:'mesh-v1',costUsd:0}]};
const good=attestDiscovery({routes,evidence},now);
assert.equal(good.verifiedCount,1);
assert.equal(good.routes[0].state,'VERIFIED');
assert.equal(good.routes[0].identity.zeroSpendVerified,true);
const meshOnly=attestDiscovery({routes,evidence:{...evidence,providerCallLedger:[{route:'free-primary',status:'ok',model:null,pipeline:'provider-mesh-v17',costUsd:0}]}},now);
assert.equal(meshOnly.routes[0].state,'VERIFIED');
assert.equal(meshOnly.routes[0].identity.version,'provider-mesh-v17');
assert.equal(meshOnly.routes[0].identity.proofArtifactDigest,null);
assert.ok(meshOnly.routes[0].identity.identityDigest.startsWith('sha256:'));
const missingAggregate=attestDiscovery({routes,evidence:{...evidence,providerCostUsd:undefined}},now);
assert.notEqual(missingAggregate.routes[0].state,'VERIFIED');
assert.equal(missingAggregate.routes[0].reasons.includes('AGGREGATE_COST_MISSING'),true);
const missingRouteCost=attestDiscovery({routes,evidence:{...evidence,providerCallLedger:[{route:'free-primary',status:'ok',model:'m',pipeline:'p'}]}},now);
assert.notEqual(missingRouteCost.routes[0].state,'VERIFIED');
assert.equal(missingRouteCost.routes[0].reasons.includes('ROUTE_COST_MISSING'),true);
const duplicateRoutes=[{id:'free-primary',configured:true,endpoint:'x'},{id:'free-primary',configured:true,endpoint:'x2'}];
const dual=attestDiscovery({routes:duplicateRoutes,evidence},now);
assert.equal(dual.verifiedCount,2);
assert.equal(dual.replacementSafe,false);
const paid=attestDiscovery({routes,evidence:{...evidence,providerCostUsd:1,providerCallLedger:[{route:'free-primary',status:'ok',model:'m',pipeline:'p',costUsd:1}]}},now);
assert.notEqual(paid.routes[0].state,'VERIFIED');
const stale=attestDiscovery({routes,evidence:{...evidence,observedAt:'2026-09-01T00:00:00Z'}},now);
assert.equal(stale.routes[0].state,'ATTESTED_STALE');

const notSuccessful=attestDiscovery({routes,evidence:{...evidence,validPatch:false}},now);
assert.notEqual(notSuccessful.routes[0].state,'VERIFIED');
assert.equal(notSuccessful.routes[0].reasons.includes('SUCCESS_NOT_PROVEN'),true);
const ambiguousTime=attestDiscovery({routes,evidence:{...evidence,generatedAt:'2026-09-08T11:59:00Z'}},now);
assert.notEqual(ambiguousTime.routes[0].state,'VERIFIED');
assert.equal(ambiguousTime.routes[0].reasons.includes('EVIDENCE_TIMESTAMP_AMBIGUOUS'),true);
const incomplete=attestDiscovery({routes,evidence:{...evidence,sourceCommit:'unknown'}},now);
assert.notEqual(incomplete.routes[0].state,'VERIFIED');
console.log('INCUMBENT_ATTESTOR_PASS');
const paidRoute=attestDiscovery({routes:[{id:'quality-cost',kind:'PAID_OR_COST_ROUTE',configured:true,endpoint:'z'}],evidence:{...evidence,providerCallLedger:[{route:'quality-cost',status:'ok',model:'m',pipeline:'p',costUsd:0}]}},now);
assert.notEqual(paidRoute.routes[0].state,'VERIFIED');
assert.equal(paidRoute.routes[0].reasons.includes('PAID_ROUTE_FORBIDDEN_IN_HARD_MODE'),true);
