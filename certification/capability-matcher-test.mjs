import assert from 'node:assert/strict';
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
const readJson = p => JSON.parse(fs.readFileSync(p,'utf8').replace(/^\uFEFF/,''));
const req = readJson('certification/benchmark-capability-requirements.json');
const providers = readJson('certification/provider-capabilities.json');
assert.equal(req.families.swefficiency.cpu, 8);
assert.equal(req.families.swefficiency.memoryMB, 16384);
assert.equal(req.families.swefficiency.maxTaskSeconds, 7200);
const ids = providers.providers.map(p => p.id);
assert.equal(new Set(ids).size, ids.length);
const semaphore = providers.providers.find(p => p.id === 'semaphore-r1-standard-8');
assert.ok(semaphore);
assert.equal(semaphore.cpu, 8);
assert.equal(semaphore.memoryMB, 16384);
assert.equal(semaphore.docker, true);
assert.notEqual(semaphore.state, 'ACTIVE');
const out = JSON.parse(execFileSync(process.execPath,['certification/capability-matcher.mjs'],{encoding:'utf8'}));
const sweff = out.results.swefficiency;
const sem = sweff.find(x => x.provider === 'semaphore-r1-standard-8');
assert.deepEqual(sem, {provider:'semaphore-r1-standard-8',eligible:false,reasons:['provider_not_active']});
assert.equal(sweff.some(x => x.eligible), false);
const gh = sweff.find(x => x.provider === 'github-public-standard');
assert.ok(gh.reasons.includes('cpu_insufficient'));
assert.ok(gh.reasons.includes('memoryMB_insufficient'));
console.log('CAPABILITY_MATCHER_TEST_PASS');